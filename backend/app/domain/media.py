"""Пределы мультимодальных материалов (RFC-0006, ADR-0012): чистые числа без ввода-вывода.

Одни и те же лимиты нужны разным слоям: `llm` ограничивает вложение одного запроса, `ingest`
режет PDF на части, сервисы показывают технические вопросы. Домен — единственное место, где они
объявлены, чтобы значения не разъехались.
"""

# Лимит одного PDF-вложения Anthropic: 32 МБ и 600 страниц на один `document`-блок (RFC-0006).
MAX_DOCUMENT_BYTES = 32 * 1024 * 1024
MAX_DOCUMENT_PAGES = 600
# Предел одного изображения: кадры уменьшаются ffmpeg-ом, но защита от чужого большого файла нужна.
MAX_IMAGE_BYTES = 16 * 1024 * 1024
# Разумный потолок страниц, которые сервер готов распознать за один запуск OCR: дальше —
# технический вопрос и просьба разделить файл, а не тихая потеря или счёт на сотни долларов.
MAX_OCR_PAGES = 500

# Возможности производных узлов (совпадают с `derivation.capability` дерева материалов).
OCR = "ocr"
VISION = "vision"
KEY_FRAMES = "frames"
MEDIA_FEED = "media_feed"
SUMMARY = "summary"

# Производные узлы, которые остаются в дереве для навигации и не идут в контекст модели:
# «Ключевые кадры» — только таймкоды без содержания, «Общая лента» дублирует расшифровку и
# описание экрана (RFC-0006, генерация качества). `summary` исключается отдельно по trust.
NAVIGATION_CAPABILITIES = frozenset({KEY_FRAMES, MEDIA_FEED})
