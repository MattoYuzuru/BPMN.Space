const EVENT_LABEL = new RegExp(
  `^(?:(${Object.keys(EVENT_KINDS).join('|')}) )?(${Object.keys(EVENT_BASES).join('|')})( \\(Non Interrupting\\))?$`,
)

/** Составные подписи событий из заголовка панели свойств: «Timer Boundary Event (Non Interrupting)». */
export function translateEventLabel(label: string): string | undefined {
  const match = EVENT_LABEL.exec(label)
  if (!match) return undefined
  const [, kind, base, nonInterrupting] = match
  const parts = [EVENT_BASES[base ?? ''] ?? base]
  if (kind) parts[0] = `${parts[0]}: ${EVENT_KINDS[kind]}`
  return nonInterrupting ? `${parts[0]} (без прерывания)` : parts[0]
}

